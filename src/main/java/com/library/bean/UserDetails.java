package com.library.bean;

public class UserDetails {

	private Integer userId;
	private String fullName;
	private String phoneNumber;
	private String photo;
	private String fatherName;
	private String preparationFor;
	private String dob;
	private String bloodGroup;
	private String email;
	private String personalNumber;
	private String emergencyNumber;
	private String presentAddress;
	private String permanentAddress;
	private String gender;
	private String aadh;
	private String password;

	public Integer getUserId() { return userId; }
	public void setUserId(Integer userId) { this.userId = userId; }
	public String getFullName() { return fullName; }
	public void setFullName(String fullName) { this.fullName = fullName; }
	public String getPhoneNumber() { return phoneNumber; }
	public void setPhoneNumber(String phoneNumber) { this.phoneNumber = phoneNumber; }
	public String getPhoto() { return photo; }
	public void setPhoto(String photo) { this.photo = photo; }
	public String getFatherName() { return fatherName; }
	public void setFatherName(String fatherName) { this.fatherName = fatherName; }
	public String getPreparationFor() { return preparationFor; }
	public void setPreparationFor(String preparationFor) { this.preparationFor = preparationFor; }
	public String getDob() { return dob; }
	public void setDob(String dob) { this.dob = dob; }
	public String getBloodGroup() { return bloodGroup; }
	public void setBloodGroup(String bloodGroup) { this.bloodGroup = bloodGroup; }
	public String getEmail() { return email; }
	public void setEmail(String email) { this.email = email; }
	public String getPersonalNumber() { return personalNumber; }
	public void setPersonalNumber(String personalNumber) { this.personalNumber = personalNumber; }
	public String getEmergencyNumber() { return emergencyNumber; }
	public void setEmergencyNumber(String emergencyNumber) { this.emergencyNumber = emergencyNumber; }
	public String getPresentAddress() { return presentAddress; }
	public void setPresentAddress(String presentAddress) { this.presentAddress = presentAddress; }
	public String getPermanentAddress() { return permanentAddress; }
	public void setPermanentAddress(String permanentAddress) { this.permanentAddress = permanentAddress; }
	public String getGender() { return gender; }
	public void setGender(String gender) { this.gender = gender; }
	public String getAadh() { return aadh; }
	public void setAadh(String aadh) { this.aadh = aadh; }
	public String getPassword() { return password; }
	public void setPassword(String password) { this.password = password; }
}
